import { COMPONENTS, DATA_CLASSIFICATIONS, EXPOSURES } from './catalog';
import type { AssessmentResult } from './result';
import type { AssessmentInput } from './validation';

// Escape characters that would let generated/user text inject Markdown structure
// (tables, HTML, links) into the downloadable report.
export function mdEscape(text: string): string {
  return text
    .replace(/\\/g, '\\\\')
    .replace(/[<>]/g, (c) => (c === '<' ? '&lt;' : '&gt;'))
    .replace(/([`*_[\]#|!])/g, '\\$1')
    .replace(/\n+/g, ' ');
}

const label = (list: readonly { id: string; label: string }[], id: string) => list.find((x) => x.id === id)?.label ?? id;

export function buildMarkdown(input: AssessmentInput, r: AssessmentResult, meta: { id: string; createdAt: string; modelId: string }): string {
  const L: string[] = [];
  L.push(`# Secure SDLC Assessment: ${mdEscape(input.title)}`, '');
  L.push('> **Training demonstration only.** Generated by AI from a synthetic description. Validate every finding with your security team. This report does not constitute approval of any application.', '');
  L.push(`- **Assessment ID:** ${meta.id}`, `- **Generated:** ${meta.createdAt}`, `- **Model:** ${mdEscape(meta.modelId)}`, `- **Overall risk:** ${r.overallRisk}`);
  L.push(`- **Exposure:** ${label(EXPOSURES, input.exposure)}`);
  L.push(`- **Components:** ${input.components.map((c) => label(COMPONENTS, c)).join(', ')}`);
  L.push(`- **Data classifications:** ${input.dataClassifications.map((d) => label(DATA_CLASSIFICATIONS, d)).join(', ')}`, '');

  L.push('## 1. Architecture summary', '', mdEscape(r.architectureSummary), '');

  L.push('## 2. STRIDE threat model', '', '| ID | STRIDE | Component | Threat | L | I | Severity | Mitigation |', '|---|---|---|---|---|---|---|---|');
  for (const t of r.threats) {
    L.push(`| ${mdEscape(t.id)} | ${t.stride} | ${mdEscape(t.component)} | ${mdEscape(t.threat)} | ${t.likelihood} | ${t.impact} | ${t.severity} | ${mdEscape(t.mitigation)} |`);
  }
  L.push('');

  L.push('## 3. Security, privacy, availability and operational risks', '');
  for (const x of r.risks) L.push(`- **[${x.severity}] ${x.category}: ${mdEscape(x.title)}** — ${mdEscape(x.description)}`);
  L.push('');

  L.push('## 4. Recommended AWS controls', '', '| Service | Control | Rationale | Addresses |', '|---|---|---|---|');
  for (const c of r.controls) L.push(`| ${mdEscape(c.service)} | ${mdEscape(c.control)} | ${mdEscape(c.rationale)} | ${c.addresses.map(mdEscape).join(', ')} |`);
  L.push('');

  L.push('## 5. Prioritized pre-deployment checklist', '');
  for (const c of r.checklist) L.push(`- [ ] **${c.priority}** ${mdEscape(c.item)} _(Owner: ${mdEscape(c.owner)}; Verify: ${mdEscape(c.verification)})_`);
  L.push('');

  L.push('## 6. Security user stories and acceptance criteria', '');
  r.userStories.forEach((u, i) => {
    L.push(`### 6.${i + 1} ${mdEscape(u.title)}`, '', mdEscape(u.story), '', '**Acceptance criteria**', '');
    for (const a of u.acceptanceCriteria) L.push(`- ${mdEscape(a)}`);
    L.push('');
  });

  if (r.assumptions.length) {
    L.push('## 7. Assumptions and open questions', '');
    for (const a of r.assumptions) L.push(`- ${mdEscape(a)}`);
    L.push('');
  }
  return L.join('\n');
}
